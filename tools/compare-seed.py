#!/usr/bin/env python3
"""Compare seed acceptance and generated output against a recorded repository revision."""
import argparse
import hashlib
import io
import json
import random
import subprocess
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cases():
    result = [(str(path.relative_to(ROOT)), path.read_bytes())
              for path in sorted((ROOT/'tests/schemas').glob('*.schema'))]
    rng = random.Random(72819)
    for case in range(72):
        names = [f'T{i}' for i in range(rng.randrange(1, 7))]
        declarations = []
        for name in names:
            is_sum = rng.choice([True, False])
            variants = []
            for variant in range(rng.randrange(1, 5) if is_sum else 1):
                fields = []
                for field in range(rng.randrange(7)):
                    ty = rng.choice(['Int', 'Bool', 'Text', *names])
                    if ty in names and rng.choice([True, False]):
                        ty = f'(many {ty})'
                    key = ' :key' if not is_sum and ty in ['Int', 'Bool', 'Text'] and rng.randrange(3) == 0 else ''
                    fields.append(f'(f{field} {ty}{key})')
                variants.append(f'({f"V{variant}" if is_sum else "node " + name} {" ".join(fields)})')
            declarations.append(f'(sum {name} {" ".join(variants)})' if is_sum else variants[0])
        result.append((f'generated-schema-{case}', '\n'.join(declarations).encode()))
    for case, source in enumerate([
        '(node A (x Missing))', '(node A (x Int) (x Bool))', '(node A) (node A)',
        '(node Int)', '(sum A)', '(sum A (B) (B))', '(sum A 12)',
        '(node A (x))', '(node A (x Int :key :key))', '(node A (x Int :unknown))',
        '(node A (x Int key))', '(node A (x (many Int)))',
        '(node A (x (many A more)))', '(node A (x (many (many A))))',
        '(sum A (B (x Int :key)) (Other))', '(unknown A)',
    ]):
        result.append((f'invalid-schema-{case}', source.encode()))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference-revision', required=True)
    args = parser.parse_args()
    revision = subprocess.check_output(['git', 'rev-parse', args.reference_revision], cwd=ROOT, text=True).strip()
    archive = subprocess.check_output(['git', 'archive', '--format=tar', revision, 'seed', 'Coil.toml'], cwd=ROOT)
    candidate = ROOT/'build/schema-seed'
    subprocess.run(['coil', 'build', 'seed/main.coil', '-o', str(candidate)], cwd=ROOT, check=True)
    records = []
    failures = []
    with tempfile.TemporaryDirectory(prefix='rewrite-seed-reference-') as directory:
        work = Path(directory)
        with tarfile.open(fileobj=io.BytesIO(archive)) as files:
            files.extractall(work, filter='data')
        reference = work/'schema-seed'
        subprocess.run(['coil', 'build', 'seed/main.coil', '-o', str(reference)], cwd=work, check=True)
        for label, source in cases():
            old = subprocess.run([str(reference)], input=source, capture_output=True)
            new = subprocess.run([str(candidate)], input=source, capture_output=True)
            accepted = old.returncode == 0
            same = accepted == (new.returncode == 0) and (old.stdout == new.stdout if accepted else not old.stdout and not new.stdout)
            records.append(dict(case=label, source=source.decode(), accepted=accepted,
                                equivalent=same, source_sha256=hashlib.sha256(source).hexdigest(),
                                generated_sha256=hashlib.sha256(new.stdout).hexdigest() if accepted else None,
                                reference_diagnostic=old.stderr.decode() if not accepted else None,
                                candidate_diagnostic=new.stderr.decode() if not accepted else None))
            if not same:
                failures.append(label)
    report = dict(reference_revision=revision,
                  scope='Acceptance/rejection and exact generated bytes on existing schema fixtures and seeded structural cases.',
                  limits='Not full Coil compatibility. Rejected inputs may have intentionally changed diagnostic wording or spans.',
                  cases=len(records), accepted=sum(r['accepted'] for r in records), failures=failures, records=records)
    (ROOT/'evidence/schema-parser-differential.json').write_text(json.dumps(report, indent=2)+'\n')
    if failures:
        raise RuntimeError(f'seed differential failures: {failures}')
    print(f'Seed differential: {len(records)} cases, 0 acceptance/output differences')


if __name__ == '__main__':
    main()
